const iconMap = {
  dashboard: DashboardIcon,
  sales: SalesIcon,
  plans: PlansIcon,
  traffic: TrafficIcon,
  meetings: MeetingsIcon,
  reports: ReportsIcon,
  users: UsersIcon,
  settings: SettingsIcon,
} as const;

type NavKey = keyof typeof iconMap;

export function AdminSidebar({ dict, lang }: AdminSidebarProps) {
  const pathname = usePathname();

  const mainNav: { key: NavKey; label: string; href: string }[] = [
    { key: "dashboard", label: dict.dashboard, href: `/${lang}/admin` },
    { key: "sales", label: dict.sales, href: `/${lang}/admin/sales` },
    { key: "plans", label: dict.plans, href: `/${lang}/admin/plans` },
    { key: "traffic", label: dict.traffic, href: `/${lang}/admin/traffic` },
    { key: "meetings", label: dict.meetings, href: `/${lang}/admin/meetings` },
    { key: "reports", label: dict.reports, href: `/${lang}/admin/reports` },
    { key: "users", label: dict.users, href: `/${lang}/admin/users` },
  ];

  function isActive(href: string): boolean {
    return pathname === href;
  }

  return (
    <aside className="hidden md:flex flex-col w-[220px] flex-shrink-0 border-r border-outline/15 min-h-[calc(100vh-88px)]">
      <nav className="flex flex-col gap-1 p-3 flex-1">
        {mainNav.map(({ key, label, href }) => {
          const active = isActive(href);
          const Icon = iconMap[key];
          return (
            <Link
              key={href}
              href={href}
              className={`dash-nav-item flex items-center gap-3 px-3 py-2.5 rounded-sm text-[13px] font-medium ${
                active
                  ? "bg-warmgray text-foreground"
                  : "text-surface-variant hover:bg-warmgray/50 hover:text-foreground"
              }`}
            >
              <Icon />
              {label}
            </Link>
          );
        })}

        <div className="mt-auto">
          <Link
            href={`/${lang}/admin/settings`}
            className={`dash-nav-item flex items-center gap-3 px-3 py-2.5 rounded-sm text-[13px] font-medium ${
              isActive(`/${lang}/admin/settings`)
                ? "bg-warmgray text-foreground"
                : "text-surface-variant hover:bg-warmgray/50 hover:text-foreground"
            }`}
          >
            <SettingsIcon />
            {dict.settings}
          </Link>
        </div>
      </nav>
    </aside>
  );
}
